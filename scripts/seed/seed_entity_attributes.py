def normalize(name):
    return name.strip().lower()


def find_motivation(name):
    n = normalize(name)
    if n in ACTOR_MOTIVATIONS:
        return ACTOR_MOTIVATIONS[n]
    # Try without spaces
    n2 = n.replace(" ", "").replace("-", "").replace("_", "")
    for k, v in ACTOR_MOTIVATIONS.items():
        k2 = k.replace(" ", "").replace("-", "").replace("_", "")
        if n2 == k2:
            return v
    return None


def find_malware_type(name):
    n = normalize(name)
    if n in MALWARE_TYPES:
        return MALWARE_TYPES[n]
    n2 = n.replace(" ", "").replace("-", "").replace("_", "")
    for k, v in MALWARE_TYPES.items():
        k2 = k.replace(" ", "").replace("-", "").replace("_", "")
        if n2 == k2:
            return v
    return None


async def main(dry_run: bool, overwrite: bool) -> None:
    async with async_session() as db:
        actors = (await db.execute(select(ThreatActor))).scalars().all()
        actor_updates = 0
        for actor in actors:
            motivation = find_motivation(actor.name)
            if not motivation or motivation == actor.motivation:
                continue
            if actor.motivation and not overwrite:
                continue
            actor.motivation = motivation
            actor_updates += 1

        print(f"Threat actor motivation updates: {actor_updates} / {len(actors)}")

        malwares = (await db.execute(select(MalwareFamily))).scalars().all()
        malware_updates = 0
        for malware in malwares:
            raw = find_malware_type(malware.name)
            if not raw:
                continue
            slug, _ = coerce_malware_type(raw)
            if not slug or slug == malware.malware_type:
                continue
            if malware.malware_type and not overwrite:
                continue
            malware.malware_type = slug
            malware_updates += 1

        print(f"Malware type updates: {malware_updates} / {len(malwares)}")

        if dry_run:
            await db.rollback()
            print("Dry run — nothing written.")
        else:
            await db.commit()
            print("Done.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="Report changes without writing.")
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Also replace attributes that already have a value (default: fill blanks only).",
    )
    args = parser.parse_args()
    asyncio.run(main(args.dry_run, args.overwrite))
