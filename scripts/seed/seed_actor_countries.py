async def main(dry_run: bool, overwrite: bool) -> None:
    by_name: dict[str, str] = {}
    for country, names in ACTOR_COUNTRIES.items():
        for name in names:
            by_name[name] = country

    async with async_session() as db:
        actors = (await db.execute(select(ThreatActor))).scalars().all()
        country_ids: dict[str, object] = {}

        matched = 0
        unresolved: set[str] = set()
        for actor in actors:
            country = by_name.get(actor.name.strip().lower())
            if not country:
                continue
            if (actor.country or actor.origin_country_id) and not overwrite:
                continue

            if country not in country_ids:
                country_ids[country] = await _resolve_country_id(db, country)
            country_id = country_ids[country]
            if country_id is None:
                unresolved.add(country)

            actor.country = country
            actor.origin_country_id = country_id
            matched += 1

        print(f"Attributed {matched} / {len(actors)} threat actors.")
        if unresolved:
            print(
                "No countries row for: "
                + ", ".join(sorted(unresolved))
                + " — run scripts/seed/seed_countries.py first to link the FK."
            )

        if dry_run:
            await db.rollback()
            print("Dry run — nothing written.")
        else:
            await db.commit()
            print("Done.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="Report changes without writing.")
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Also replace attribution that is already set (default: fill blanks only).",
    )
    args = parser.parse_args()
    asyncio.run(main(args.dry_run, args.overwrite))
