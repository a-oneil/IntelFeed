def _full_variables(theme: dict) -> dict:
    heatmap = theme.get("heatmap") or (DARK_HEATMAP if theme["dark"] else LIGHT_HEATMAP)
    return {**theme["vars"], **heatmap}


def upgrade() -> None:
    conn = op.get_bind()
    for theme in THEMES:
        exists = conn.execute(
            sa.text("SELECT 1 FROM themes WHERE name = :name AND is_system = TRUE"),
            {"name": theme["name"]},
        ).first()
        if exists:
            continue
        conn.execute(
            sa.text(
                "INSERT INTO themes (id, name, css_variables, is_system, created_at) "
                "VALUES (gen_random_uuid(), :name, :css_variables, TRUE, NOW())"
            ),
            {"name": theme["name"], "css_variables": json.dumps(_full_variables(theme))},
        )


def downgrade() -> None:
    conn = op.get_bind()
    for theme in THEMES:
        conn.execute(
            sa.text("DELETE FROM themes WHERE name = :name AND is_system = TRUE"),
            {"name": theme["name"]},
        )
