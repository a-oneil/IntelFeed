                code.lowercase()
            }
            return when (resolvedCode) {
                "es" -> SpanishStrings
                "fr" -> FrenchStrings
                "de" -> GermanStrings
                "uk" -> UkrainianStrings
                "ru" -> RussianStrings
                "zh" -> ChineseStrings
                "ja" -> JapaneseStrings
                "pt" -> PortugueseStrings
                "it" -> ItalianStrings
                else -> EnglishStrings
            }
