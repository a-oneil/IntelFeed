def _enum(spec: dict) -> list | None:
    e = spec.get("enum")
    if e is None and spec.get("type") == "array":
        e = (spec.get("items") or {}).get("enum")
    if not e or "?" in e:
        return None
    return list(e)


def signature(name: str, definition: dict) -> str:
    props = (definition.get("input_schema") or {}).get("properties", {})
    required = set((definition.get("input_schema") or {}).get("required", []))
    parts = []
    for p, spec in props.items():
        t = spec.get("type", "string")
        t = {
            "string": "str",
            "integer": "int",
            "number": "num",
            "boolean": "bool",
            "array": "list",
            "object": "obj",
        }.get(t, t)
        s = f"{p}{'*' if p in required else ''}:{t}"
        e = _enum(spec)
        if e:
            s += "[" + "|".join(map(str, e[:14])) + ("|…" if len(e) > 14 else "") + "]"
        if spec.get("default") not in (None, "", [], {}):
            s += f"={spec['default']}"
        parts.append(s)
    return f"{name}({', '.join(parts)})"


def first_sentence(text: str, cap: int = 170) -> str:
    text = " ".join(text.split())
    m = re.search(r"(?<=[.!?])\s", text)
    s = text[: m.start()] if m and m.start() < cap else text
    return s if len(s) <= cap else s[: cap - 1].rsplit(" ", 1)[0] + "…"


def _coerce(value: Any, spec: dict, pname: str, sig: str) -> Any:
    t = spec.get("type")
    try:
        if t == "integer" and not isinstance(value, bool):
            value = int(float(value))
        elif t == "number" and not isinstance(value, bool):
            value = float(value)
        elif t == "boolean" and isinstance(value, str):
            value = value.strip().lower() in ("1", "true", "yes", "on")
        elif t == "array" and isinstance(value, str):
            value = [v.strip() for v in value.split(",") if v.strip()]
        elif t == "string" and isinstance(value, (int, float)) and not isinstance(value, bool):
            value = str(value)
    except (TypeError, ValueError):
        raise ToolError(f"'{pname}' must be {t}. Usage: {sig}")
    allowed = _enum(spec)
    if allowed:
        vals = value if isinstance(value, list) else [value]
        fixed = []
        for v in vals:
            match = next((a for a in allowed if str(a).lower() == str(v).strip().lower()), None)
            if match is None:
                raise ToolError(f"'{pname}' must be one of {allowed}, got {v!r}.")
            fixed.append(match)
        value = fixed if isinstance(value, list) else fixed[0]
    return value


def check_args(name: str, definition: dict, args: dict) -> tuple[dict, list[str]]:
    schema = definition.get("input_schema") or {}
    props = schema.get("properties", {})
    sig = signature(name, definition)
    clean, ignored = {}, []
    for k, v in (args or {}).items():
        if v is None or v == "":
            continue
        if k not in props:
            ignored.append(k)
            continue
        clean[k] = _coerce(v, props[k], k, sig)
    missing = [r for r in schema.get("required", []) if r not in clean]
    if missing:
        raise ToolError(f"Missing required argument(s) {missing}. Usage: {sig}")
    # Keep list sizes small unless the model asked for more.
    if "limit" in props and "limit" not in clean:
        clean["limit"] = DEFAULT_LIMIT
    if "limit_per_type" in props and "limit_per_type" not in clean:
        clean["limit_per_type"] = PIVOT_ROWS_PER_TYPE
    notes = [f"ignored unknown argument(s) {ignored}; usage: {sig}"] if ignored else []
    return clean, notes


