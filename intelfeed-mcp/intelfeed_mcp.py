UUID_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")
HANDLE_RE = re.compile(r"^u\d+$")


class Handles:
    def __init__(self) -> None:
        self._by_uuid: dict[str, str] = {}
        self._by_handle: dict[str, str] = {}
        self._lock = threading.Lock()

    def short(self, uuid: str) -> str:
        key = uuid.lower()
        with self._lock:
            h = self._by_uuid.get(key)
            if h is None:
                h = f"u{len(self._by_uuid) + 1}"
                self._by_uuid[key] = h
                self._by_handle[h] = key
            return h

    def resolve(self, value: Any) -> Any:
        """Replace handles with UUIDs anywhere in an argument value."""
        if isinstance(value, str):
            v = value.strip()
            if HANDLE_RE.match(v):
                full = self._by_handle.get(v)
                if full is None:
                    raise ToolError(
                        f"Unknown id handle '{v}'. Handles reset when the server restarts; "
                        "search again to get fresh ids."
                    )
                return full
            return value
        if isinstance(value, list):
            return [self.resolve(v) for v in value]
        if isinstance(value, dict):
            return {k: self.resolve(v) for k, v in value.items()}
        return value


