class IntelFeed:
    """IntelFeed API access (login, token refresh, tool calls) plus the tool registry. Thread-safe."""

    def __init__(self, api_url: str | None = None, username: str | None = None, password: str | None = None):
        self.api_url = (api_url or os.environ.get("INTELFEED_API_URL") or "").strip().rstrip("/")
        try:
            validate_api_url(self.api_url)
            self.config_error = ""
        except ValueError as e:
            self.config_error = str(e)
        self.username = os.environ.get("INTELFEED_USERNAME", "") if username is None else username
        self.password = os.environ.get("INTELFEED_PASSWORD", "") if password is None else password
        # A supplied token is the whole credential: no login, no refresh.
        self._static_token = os.environ.get("INTELFEED_TOKEN", "").strip() or None
        self._access: str | None = self._static_token
        self._refresh: str | None = None
        self._lock = threading.Lock()
        self._registry: dict[str, dict] | None = None
        self._registry_lock = threading.Lock()  # concurrent first calls share one fetch
        self.registry_source = "not loaded"

    def _http(self, method: str, path: str, body: dict | None = None, *, auth: bool = True, timeout: int = 120):
        if self.config_error:
            raise ToolError(self.config_error + " Tell the user.")
        headers = {"User-Agent": f"IntelFeed-MCP/{SERVER_VERSION}"}
        data = None
        if body is not None:
            data = json.dumps(body).encode("utf-8")
            headers["Content-Type"] = "application/json"
        if auth and self._access:
            headers["Authorization"] = f"Bearer {self._access}"
        req = urllib.request.Request(self.api_url + path, data=data, headers=headers, method=method)
        try:
            with _OPENER.open(req, timeout=timeout) as resp:
                status, raw = resp.status, resp.read().decode("utf-8", errors="replace")
        except urllib.error.HTTPError as e:
            status, raw = e.code, e.read().decode("utf-8", errors="replace")
        except urllib.error.URLError as e:
            raise ToolError(f"IntelFeed API unreachable at {self.api_url} ({e.reason}). Try again later.")
        except TimeoutError:
            raise ToolError(f"IntelFeed took longer than {timeout} s to answer. Try a narrower query.")
        if 300 <= status < 400:
            raise ToolError(
                f"IntelFeed answered {self.api_url}{path} with a redirect (HTTP {status}), which is not followed "
                "so credentials can't be sent elsewhere. Set INTELFEED_API_URL to the final https:// address. "
                "Tell the user."
            )
        try:
            return status, json.loads(raw)
        except json.JSONDecodeError:
            return status, raw

    def _login(self) -> None:  # caller holds self._lock
        if self._static_token:
            raise ToolError("IntelFeed refused this session's token (expired or revoked). Tell the user.")
        if not self.username or not self.password:
            raise ToolError(
                "IntelFeed credentials are not configured: set INTELFEED_USERNAME and INTELFEED_PASSWORD "
                f"(environment or {SCRIPT_DIR / '.env'}) and restart the MCP server. Tell the user."
            )
        status, data = self._http(
            "POST", "/api/auth/login", {"username": self.username, "password": self.password}, auth=False, timeout=30
        )
        if status != 200 or not isinstance(data, dict) or "access_token" not in data:
            raise ToolError(f"IntelFeed login failed (HTTP {status}); check the username and password. Tell the user.")
        self._access, self._refresh = data["access_token"], data.get("refresh_token")

    def _renew(self) -> None:  # caller holds self._lock
        if self._refresh and not self._static_token:
            status, data = self._http(
                "POST", "/api/auth/refresh", {"refresh_token": self._refresh}, auth=False, timeout=30
            )
            if status == 200 and isinstance(data, dict) and "access_token" in data:
                self._access, self._refresh = data["access_token"], data.get("refresh_token", self._refresh)
                return
        self._login()

    def _authed(self, method: str, path: str, body: dict | None = None, timeout: int = 120):
        with self._lock:
            if not self._access:
                self._login()
        status, data = self._http(method, path, body, timeout=timeout)
        if status == 401:
            with self._lock:
                self._renew()
            status, data = self._http(method, path, body, timeout=timeout)
        return status, data

    def execute(self, tool: str, args: dict) -> str:
        status, data = self._authed("POST", "/api/tools/execute", {"tool_name": tool, "args": args})
        if status == 429:
            raise ToolError("IntelFeed rate limit reached; wait a minute before the next call.")
        if status != 200 or not isinstance(data, dict) or "result" not in data:
            detail = data.get("message") or data.get("detail") if isinstance(data, dict) else data
            raise ToolError(f"IntelFeed returned HTTP {status} for {tool}: {str(detail)[:300]}")
        result = data["result"]
        return result if isinstance(result, str) else json.dumps(result, default=str, ensure_ascii=False)

    def registry(self) -> dict[str, dict]:
        """Tool definitions keyed by name: live from GET /api/tools/tools, else the bundled snapshot."""
        if self._registry is not None:
            return self._registry
        with self._registry_lock:
            if self._registry is None:
                self._registry = self._load_registry()
        return self._registry

    def _load_registry(self) -> dict[str, dict]:
        defs = None
        try:
            status, data = self._authed("GET", "/api/tools/tools", timeout=30)
            if status == 200 and isinstance(data, list) and data:
                defs, self.registry_source = data, "live"
            else:
                log(f"live registry: HTTP {status}; using {SNAPSHOT_PATH.name}")
        except ToolError as e:
            log(f"live registry unavailable ({e}); using {SNAPSHOT_PATH.name}")
        if not defs:
            defs = json.loads(SNAPSHOT_PATH.read_text(encoding="utf-8"))
            self.registry_source = "snapshot"
        registry = {d["name"]: d for d in defs}
        log(f"registry: {len(registry)} tools ({self.registry_source})")
        return registry

    def is_readable(self, tool: str) -> bool:
        d = self.registry().get(tool)
        return (
            tool in READ_ONLY_TOOLS
            and d is not None
            and d.get("mutating") is False
            and tool not in PERSISTING_READ_TOOLS
        )

    def is_allowed_write(self, tool: str) -> bool:
        return ALLOW_WRITES and tool in WRITE_TOOLS and tool in self.registry()


