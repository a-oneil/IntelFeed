#!/usr/bin/env python3
"""IntelFeed MCP server, built for small local models (LM Studio, Ollama front-ends, ...).

It exposes IntelFeed's tool registry (the one behind POST /api/tools/execute) over the
Model Context Protocol on stdio, but shaped so a local model's context window survives:

* **A small fixed tool list.** Nine tools (~1.3k tokens) instead of the registry's 170
  (~27k tokens). The list never changes during a session, so the model server can keep
  reusing its cached prompt prefix.
* **Skills, loaded on demand.** `load_skill(name)` returns a short playbook plus the
  signatures of the extra tools for that task (skills/*.md); `call_tool(tool, args)`
  then runs any of them. The model only pays for the tools it is actually using.
* **Shaped results.** Every tool result is cut to a budget (~2k tokens by default):
  HTML stripped, empty/noise fields dropped, dates shortened, long text and long lists
  trimmed, uniform lists rendered as compact tables. The untrimmed result is kept and
  can be paged with `read_more(ref, page)`.
* **Short ids.** UUIDs (≈25 tokens each, and easy for a small model to garble) are
  replaced with handles like `u12`; handles are translated back in tool arguments.
* **Read-only by default.** A tool runs only if it is on the reviewed READ_ONLY_TOOLS list
  below *and* the registry marks it non-mutating, so a new or mis-flagged backend tool stays
  blocked until someone reviews it. `INTELFEED_MCP_ALLOW_WRITES=1` adds a separate
  `write_action` tool limited to a short list of low-risk writes (notes, tags, stars,
  watches, campaigns); merges, deletes and feed/automation changes are never exposed.

The tool list comes from the live registry (GET /api/tools/tools); registry.json next to
this file is the fallback, generated by scripts/dev/sync_skill_clis.py. Stdlib only.

Configuration (environment, or a .env file next to this script — see .env.example):
    INTELFEED_API_URL / INTELFEED_USERNAME / INTELFEED_PASSWORD
    INTELFEED_TOKEN              a ready-made bearer token, used instead of logging in (the
                                 backend passes a short-lived read-only one when its Claude CLI
                                 provider runs this server); never refreshed, never mixed with a password
    INTELFEED_MCP_ALLOW_WRITES   1 to expose write_action (default off)
    INTELFEED_MCP_WRITE_TOOLS    comma list that narrows (never extends) the writes write_action allows
    INTELFEED_ALLOW_INSECURE_HTTP  1 to allow plain http:// to a non-loopback host (e.g. a LAN dev box)
    INTELFEED_MCP_RESULT_CHARS   per-result character budget (default 7000 ≈ 2k tokens)
    INTELFEED_MCP_DEFAULT_LIMIT  default `limit` for list/search tools (default 10)
    INTELFEED_MCP_LOG            optional path to append a call log to

Run by an MCP client, e.g. LM Studio's ~/.lmstudio/mcp.json:
    {"mcpServers": {"intelfeed": {"command": "python3",
                                  "args": ["/path/to/IntelFeed/intelfeed-mcp/intelfeed_mcp.py"]}}}
"""

