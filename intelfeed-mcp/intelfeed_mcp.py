class Server:
    def __init__(self, intelfeed: IntelFeed | None = None) -> None:
        self.intelfeed = intelfeed or IntelFeed()
        self.handles = Handles()
        self.store = ResultStore()
        self.skills = load_skills()
        self.tools = [dict(t) for t in CORE_TOOLS]
        for t in self.tools:
            if t["name"] == "load_skill":
                listing = "; ".join(f"{s['name']}: {s['description']}" for s in self.skills.values())
                t["description"] = (
                    "Load a playbook with the extra tools for a task (use call_tool to run them). Skills — " + listing
                )
                t["inputSchema"]["properties"]["name"]["enum"] = list(self.skills)
        if ALLOW_WRITES:
            self.tools.append(WRITE_TOOL_DEF)

    # -- result formatting -------------------------------------------------

    def format_result(
        self, raw: str, extra_notes: list[str] | None = None, *, tool: str | None = None, args: dict | None = None
    ) -> tuple[str, bool]:
        data = parse_result(raw)
        is_error = isinstance(data, dict) and set(data) <= {"error", "detail"} and "error" in data
        data = project(tool, data, args)
        notes = ShapeNotes()
        shaped = shape(data, self.handles, notes)
        if shaped is _DROP:
            text = "(no results)"
        else:
            text = "\n".join(render(shaped)) if not isinstance(shaped, str) else shaped
        footer = list(extra_notes or [])
        if notes.trimmed or len(text) > RESULT_CHARS:
            full = shape(data, self.handles, ShapeNotes(), full=True)
            full_text = "\n".join(render(full)) if not isinstance(full, str) else full
            ref, pages = self.store.put(full_text)
            if len(text) > RESULT_CHARS:
                text = paginate(text, RESULT_CHARS)[0]
            if pages == 1:
                footer.append(f'[shortened — full version: read_more(ref="{ref}")]')
            else:
                footer.append(f'[shortened — full version has {pages} pages: read_more(ref="{ref}", page=1..{pages})]')
        if footer:
            text += "\n" + "\n".join(footer)
        return text, is_error

    # -- IntelFeed calls -----------------------------------------------------

    def run_registry_tool(self, tool: str, args: dict, *, write: bool = False) -> tuple[str, bool]:
        registry = self.intelfeed.registry()
        definition = registry.get(tool)
        if definition is None:
            close = [n for n in registry if tool.split("_")[-1] in n][:8]
            raise ToolError(
                f"No tool named '{tool}'."
                + (f" Similar: {close}." if close else "")
                + " load_skill lists the tools for each task."
            )
        if write:
            if not self.intelfeed.is_allowed_write(tool):
                raise ToolError(f"'{tool}' is not an allowed write action. Allowed: {list(WRITE_TOOLS)}.")
        elif not self.intelfeed.is_readable(tool):
            if definition.get("mutating") or tool in PERSISTING_READ_TOOLS:
                hint = (
                    " Use write_action."
                    if self.intelfeed.is_allowed_write(tool)
                    else (" Writes are disabled in this connection; tell the user to do it in the IntelFeed web app.")
                )
                raise ToolError(f"'{tool}' changes data, so call_tool cannot run it.{hint}")
            raise ToolError(
                f"'{tool}' is not on this connection's reviewed read-only list (READ_ONLY_TOOLS), so it can't run."
            )
        args = self.handles.resolve(args or {})
        clean, notes = check_args(tool, definition, args)
        started = time.monotonic()
        raw = self.intelfeed.execute(tool, clean)
        text, is_error = self.format_result(raw, notes, tool=tool, args=clean)
        # argument names only: values (note text, queries) can be private
        log(
            f"{tool}({', '.join(sorted(clean))}) -> {len(raw)} chars raw, "
            f"{len(text)} shown, {time.monotonic() - started:.1f}s"
        )
        return text, is_error

    def resolve_entity(self, entity_type: str, value: str, *, public_id_ok: bool = False) -> str:
        """A handle or UUID passes through (and a CVE/CWE/technique id when the target tool takes one);
        anything else is looked up by name with search_entities."""
        value = str(value).strip()
        if HANDLE_RE.match(value):
            return self.handles.resolve(value)
        if UUID_RE.match(value):
            return value
        pattern = PUBLIC_ID_TYPES.get(entity_type)
        if pattern and pattern.match(value) and public_id_ok:
            return value.upper()
        raw = self.intelfeed.execute("search_entities", {"query": value, "limit": 20})
        data = parse_result(raw)
        items = data.get("results", []) if isinstance(data, dict) else []
        want = entity_type.replace("_", "")
        typed = [
            i
            for i in items
            if isinstance(i, dict) and str(i.get("type", "")).replace("_", "").rstrip("s").startswith(want.rstrip("s"))
        ]
        low = value.lower()

        def names(i: dict) -> list[str]:
            vals = [i.get(k) for k in ("name", "title", "cve_id", "cwe_id", "technique_id")]
            vals += list(i.get("aliases") or [])
            return [str(v).lower() for v in vals if v]

        exact = [i for i in typed if low in names(i)]
        pick = exact if exact else typed
        if len(pick) == 1 or (exact and len({i["id"] for i in exact}) == 1):
            return pick[0]["id"]
        if not pick:
            raise ToolError(f"No {entity_type} named '{value}'. Try search_entities with another name or alias.")
        choices = ", ".join(f"{self.handles.short(i['id'])} = {i.get('name') or i.get('title')}" for i in pick[:8])
        raise ToolError(
            f"'{value}' matches several {entity_type} entries: {choices}. Call again with one of these ids."
        )

    # -- MCP tool dispatch -----------------------------------------------------

    def call(self, name: str, args: dict) -> tuple[str, bool]:
        args = args or {}
        if name in ("search_entries", "search_entities", "get_entry", "get_trending_entities"):
            return self.run_registry_tool(name, args)
        if name == "get_profile":
            etype = str(args.get("entity_type", "")).strip().lower()
            if etype not in PROFILE_TOOLS:
                raise ToolError(
                    f"entity_type must be one of {list(PROFILE_TOOLS)}. For tools, vendors, products "
                    "or countries use pivot_entity or search_entities."
                )
            if not args.get("id"):
                raise ToolError("id is required.")
            tool, param = PROFILE_TOOLS[etype]
            return self.run_registry_tool(tool, {param: self.resolve_entity(etype, args["id"], public_id_ok=True)})
        if name == "pivot_entity":
            etype = str(args.get("entity_type", "")).strip().lower()
            if not args.get("entity_id"):
                raise ToolError("entity_id is required.")
            call_args = {k: v for k, v in args.items() if k != "entity_id"}
            call_args["entity_id"] = self.resolve_entity(etype, args["entity_id"])
            return self.run_registry_tool("pivot_entity", call_args)
        if name == "load_skill":
            return self.load_skill(str(args.get("name", ""))), False
        if name == "call_tool":
            tool = str(args.get("tool", "")).strip()
            tool_args = args.get("args") or {}
            if isinstance(tool_args, str):
                try:
                    tool_args = json.loads(tool_args) if tool_args.strip() else {}
                except json.JSONDecodeError:
                    raise ToolError('args must be a JSON object, e.g. {"days": 30}.')
            return self.run_registry_tool(tool, tool_args)
        if name == "read_more":
            return self.read_more(str(args.get("ref", "")), args.get("page", 1)), False
        if name == "write_action" and ALLOW_WRITES:
            return self.run_registry_tool(str(args.get("tool", "")), args.get("args") or {}, write=True)
        raise ToolError(f"Unknown tool '{name}'.")

    def load_skill(self, name: str) -> str:
        skill = self.skills.get(name.strip().lower().replace(" ", "-").replace("_", "-"))
        if not skill:
            return "Unknown skill. Available: " + ", ".join(self.skills)
        registry = self.intelfeed.registry()
        core = {t["name"] for t in CORE_TOOLS}
        lines = [f"# Skill: {skill['name']}", skill["body"]]
        tool_lines = []
        for tool in skill["tools"]:
            d = registry.get(tool)
            if d is None or tool in core:  # core tools are already in the model's tool list
                continue
            usable = self.intelfeed.is_readable(tool) or self.intelfeed.is_allowed_write(tool)
            if not usable:
                continue
            tool_lines.append(f"- {signature(tool, d)} — {first_sentence(d.get('description', ''))}")
        if tool_lines:
            how = "write_action(tool, args)" if skill["name"] == "writes" else "call_tool(tool, args)"
            lines.append(f"\n## Tools (run with {how}; * = required)\n" + "\n".join(tool_lines))
        return "\n".join(lines)

    def read_more(self, ref: str, page: Any) -> str:
        pages = self.store.get(ref.strip())
        if pages is None:
            raise ToolError(f"No stored result '{ref}' (only the last 50 are kept). Run the tool again.")
        try:
            n = int(page)
        except (TypeError, ValueError):
            n = 1
        n = min(max(n, 1), len(pages))
        more = f"\n[page {n}/{len(pages)}" + (
            f' — next: read_more(ref="{ref}", page={n + 1})]' if n < len(pages) else "]"
        )
        return pages[n - 1] + more


# ---------------------------------------------------------------------------
# JSON-RPC over stdio
# ---------------------------------------------------------------------------


class Transport:
    def __init__(self, server: Server, out=None) -> None:
        self.server = server
        self.out = out or sys.stdout
        self._write_lock = threading.Lock()
        self._calls: set[threading.Thread] = set()

    def send(self, msg: dict) -> None:
        line = json.dumps(msg, ensure_ascii=False, separators=(",", ":"))
        with self._write_lock:
            self.out.write(line + "\n")
            self.out.flush()

    def reply(self, msg_id: Any, result: dict) -> None:
        self.send({"jsonrpc": "2.0", "id": msg_id, "result": result})

    def error(self, msg_id: Any, code: int, message: str) -> None:
        self.send({"jsonrpc": "2.0", "id": msg_id, "error": {"code": code, "message": message}})

    def handle(self, msg: dict) -> None:
        method = msg.get("method")
        msg_id = msg.get("id")
        is_request = "id" in msg
        params = msg.get("params") or {}
        if method is None:
            return  # a response to something we never send
        if not is_request:
            return  # notifications: initialized, cancelled, ... — nothing to do
        if method == "initialize":
            requested = params.get("protocolVersion")
            version = requested if requested in PROTOCOL_VERSIONS else PROTOCOL_VERSIONS[0]
            self.reply(
                msg_id,
                {
                    "protocolVersion": version,
                    "capabilities": {"tools": {"listChanged": False}},
                    "serverInfo": {"name": SERVER_NAME, "version": SERVER_VERSION},
                    "instructions": INSTRUCTIONS,
                },
            )
        elif method == "ping":
            self.reply(msg_id, {})
        elif method == "tools/list":
            self.reply(msg_id, {"tools": self.server.tools})
        elif method == "tools/call":
            worker = threading.Thread(target=self._call, args=(msg_id, params), daemon=True)
            self._calls.add(worker)
            worker.start()
        elif method in ("resources/list", "resources/templates/list", "prompts/list"):
            key = {
                "resources/list": "resources",
                "resources/templates/list": "resourceTemplates",
                "prompts/list": "prompts",
            }[method]
            self.reply(msg_id, {key: []})
        else:
            self.error(msg_id, -32601, f"Method not found: {method}")

    def _call(self, msg_id: Any, params: dict) -> None:
        name = params.get("name", "")
        try:
            text, is_error = self.server.call(name, params.get("arguments") or {})
        except ToolError as e:
            text, is_error = f"Error: {e}", True
            log(f"{name}: {e}")
        except Exception as e:  # noqa: BLE001 — never let one call kill the server
            text, is_error = f"Error: internal failure in {name} ({type(e).__name__}: {e})", True
            log(traceback.format_exc())
        self.reply(msg_id, {"content": [{"type": "text", "text": text}], "isError": is_error})
        self._calls.discard(threading.current_thread())

    def serve(self, stream=None) -> None:
        stream = stream or sys.stdin
        for line in stream:
            line = line.strip()
            if not line:
                continue
            try:
                msg = json.loads(line)
            except json.JSONDecodeError:
                self.error(None, -32700, "Parse error")
                continue
            for m in msg if isinstance(msg, list) else [msg]:
                if isinstance(m, dict):
                    try:
                        self.handle(m)
                    except Exception as e:  # noqa: BLE001
                        log(traceback.format_exc())
                        if "id" in m:
                            self.error(m.get("id"), -32603, f"Internal error: {e}")
        # stdin closed: let in-flight tool calls send their replies before exiting.
        for worker in list(self._calls):
            worker.join(timeout=150)


def main() -> None:
    sys.stdin.reconfigure(encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    rpc_out = sys.stdout
    sys.stdout = sys.stderr  # a stray print() must not corrupt the JSON-RPC stream
    server = Server()
    log(
        f"started: {len(server.tools)} tools, {len(server.skills)} skills, writes "
        f"{'on' if ALLOW_WRITES else 'off'}, IntelFeed {server.intelfeed.api_url}"
    )
    Transport(server, out=rpc_out).serve(sys.stdin)


if __name__ == "__main__":
    main()
