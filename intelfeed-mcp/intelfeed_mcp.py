def validate_api_url(url: str) -> str:
    """https://, or http:// to this machine; anything else would send the password in clear text."""
    if not url:
        raise ValueError("INTELFEED_API_URL is not set. Point it at your instance, e.g. https://intelfeed.example.com.")
    parts = urllib.parse.urlsplit(url)
    if parts.scheme == "https" and parts.hostname:
        return url
    if parts.scheme == "http" and parts.hostname:
        if parts.hostname in ("localhost", "127.0.0.1", "::1") or _env_flag("INTELFEED_ALLOW_INSECURE_HTTP"):
            return url
        raise ValueError(
            f"INTELFEED_API_URL {url} uses plain http:// to another host, which would send your password "
            "unencrypted. Use https://, or set INTELFEED_ALLOW_INSECURE_HTTP=1 for a trusted LAN."
        )
    raise ValueError(f"INTELFEED_API_URL {url!r} must start with https:// (or http://localhost).")


class _RefuseRedirects(urllib.request.HTTPRedirectHandler):
    """urllib re-sends every header, Authorization included, to wherever a redirect points —
    even another host over plain HTTP. The API never redirects, so treat any redirect as an error."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


_OPENER = urllib.request.build_opener(_RefuseRedirects)


class ToolError(Exception):
    """A problem the model can fix (bad args, unknown id...); returned as an isError result."""


